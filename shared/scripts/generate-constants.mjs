#!/usr/bin/env node
/**
 * Emits the pillar and subject constants, in TypeScript and in Python, from the
 * JSON in shared/data/.
 *
 * WHY A GENERATOR AND NOT AN IMPORT. The web app and the mobile app can both
 * `import` the JSON directly; the Flask backend cannot, and that asymmetry is
 * what let seven copies of the pillar vocabulary accumulate. A TypeScript file
 * cannot be canonical for a Python process. JSON can be canonical for both, so
 * the JSON is the source and each language gets a file emitted from it.
 *
 * WHAT EACH LANGUAGE GETS IS NOT THE SAME, on purpose:
 *
 *   - TypeScript gets the cross-platform identity of a pillar (key, labels,
 *     colour, description) and nothing else. It does NOT get the `legacy`
 *     vocabulary, which only the backend has to accept.
 *   - Python gets that plus `legacy`, and does NOT get subject descriptions or
 *     accent colours, which belong to the pickers the two clients draw. The
 *     backend has its own SCHOOL_SUBJECT_DESCRIPTIONS written for quest
 *     creators — a different audience, deliberately a different list.
 *
 * A surface that cannot read a field cannot drift from it.
 *
 * WHAT THIS DOES NOT OWN: display ORDER at a call site. The canonical order is
 * here, but three consumers legitimately render a different one, and each of
 * those orders is observable — /api/pillars returns `keys` as an array, the
 * treehouse endpoint builds its category list by iterating, and a 400 body
 * joins the list into a sentence. Those modules declare their own order and
 * backend/tests/unit/test_pillar_constants_generated.py checks that every such
 * order is a permutation of the canonical keys. Ownership of the VOCABULARY is
 * the thing that stops copies drifting; ownership of the order is not.
 *
 * Usage:
 *   node shared/scripts/generate-constants.mjs           # write the files
 *   node shared/scripts/generate-constants.mjs --check   # fail if they drift
 *
 * `--check` is what CI runs (tests-web.yml). It needs no npm install: this
 * script has no dependencies beyond Node itself, which is the reason it can sit
 * in a job that installs only the web app.
 */

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const SHARED = join(HERE, '..');
const REPO = join(SHARED, '..');

const readJson = (p) => JSON.parse(readFileSync(p, 'utf8'));

const pillars = readJson(join(SHARED, 'data', 'pillars.json')).pillars;
const subjects = readJson(join(SHARED, 'data', 'subjects.json')).subjects;
const credits = readJson(join(SHARED, 'data', 'credits.json'));
const pricing = readJson(join(SHARED, 'data', 'pricing.json'));

/** Single-quoted Python string literal. */
const py = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
/**
 * Python float literal. Always spells the decimal point: the values these
 * replace were written 4.0 / 0.5 / 24.0, and JSON gives them back as 4 and 24.
 * Python would then round(4, 2) -> int, and jsonify would put `4` in a response
 * where `4.0` used to be. Same number, different bytes on the wire.
 */
const pyf = (n) => (Number.isInteger(n) ? `${n}.0` : String(n));
/** Single-quoted TypeScript string literal. */
const ts = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

const BANNER = (source) => `Generated by shared/scripts/generate-constants.mjs from ${source}.
DO NOT EDIT. Edit the JSON and run \`npm run generate\` from the repo root.
CI runs \`npm run generate:check\`, so an edit here fails the build.`;

// ---------------------------------------------------------------- TypeScript

function tsPillars() {
  const rows = pillars
    .map(
      (p) => `  {
    key: ${ts(p.key)},
    label: ${ts(p.label)},
    shortLabel: ${ts(p.shortLabel)},
    color: ${ts(p.color)},
    description: ${ts(p.description)},
  },`,
    )
    .join('\n');

  return `/**
 * ${BANNER('shared/data/pillars.json').split('\n').join('\n * ')}
 *
 * The typed front door is ../pillars.ts, which adds the lookup helpers. Import
 * that, not this.
 */

export interface PillarRecord {
  key: string;
  /** Full name, for anywhere with room for it. */
  label: string;
  /** For cramped spaces — radar axes, mobile filter chips. Often identical. */
  shortLabel: string;
  /** Hex. The single source; see the note in data/pillars.json about the web app. */
  color: string;
  description: string;
}

/** Canonical display order. */
export const PILLARS_DATA: readonly PillarRecord[] = [
${rows}
];
`;
}

function tsSubjects() {
  const rows = subjects
    .map(
      (s) => `  {
    key: ${ts(s.key)},
    name: ${ts(s.name)},
    description: ${ts(s.description)},
    accent: ${ts(s.accent)},
  },`,
    )
    .join('\n');

  return `/**
 * ${BANNER('shared/data/subjects.json').split('\n').join('\n * ')}
 *
 * The typed front door is ../subjects.ts, which adds the lookup helpers. Import
 * that, not this.
 */

export interface SubjectRecord {
  key: string;
  name: string;
  description: string;
  accent: string;
}

/** In transcript order, which is the order the backend enum declares. */
export const SUBJECTS_DATA: readonly SubjectRecord[] = [
${rows}
];
`;
}

// -------------------------------------------------------------------- Python

function pyDict(pairs, indent = '    ') {
  return pairs.map(([k, v]) => `${indent}${py(k)}: ${py(v)},`).join('\n');
}

function pyPillars() {
  const keys = pillars.map((p) => `    ${py(p.key)},`).join('\n');

  // One flat alias -> key map, which is what normalize_pillar_name needs. The
  // three groups are emitted in canonical pillar order rather than in the order
  // utils/pillar_utils.py happened to declare them; it is a lookup dict, and no
  // two entries differ only by case, so the iteration order in that function's
  // case-insensitive fallback cannot change which key wins.
  const aliasRows = [];
  for (const p of pillars) {
    for (const a of p.legacy.aliases) aliasRows.push([a, p.key]);
  }
  for (const p of pillars) aliasRows.push([p.legacy.displayName, p.key]);

  return `"""${BANNER('shared/data/pillars.json')}

The \`legacy\` names below are the pre-2025 vocabulary. The backend still has to
accept them: rows written before the rename are still in the database, and the
AI prompts were written against the old display names. Neither client needs
them, so the TypeScript output does not carry them.
"""

# Canonical order. A consumer that renders a DIFFERENT order declares that order
# itself -- see the note in shared/scripts/generate-constants.mjs about why.
PILLAR_KEYS = (
${keys}
)

PILLAR_LABELS = {
${pyDict(pillars.map((p) => [p.key, p.label]))}
}

PILLAR_COLORS = {
${pyDict(pillars.map((p) => [p.key, p.color]))}
}

PILLAR_DESCRIPTIONS = {
${pyDict(pillars.map((p) => [p.key, p.description]))}
}

# The '&' display names the old UI showed and the AI prompts still speak.
PILLAR_LEGACY_DISPLAY_NAMES = {
${pyDict(pillars.map((p) => [p.key, p.legacy.displayName]))}
}

# Every old spelling of a pillar -> its current key. Underscore keys, short keys
# and display names, all in one map, because every caller wants the same answer.
PILLAR_LEGACY_ALIASES = {
${pyDict(aliasRows)}
}
`;
}

function pySubjects() {
  const keys = subjects.map((s) => `    ${py(s.key)},`).join('\n');

  return `"""${BANNER('shared/data/subjects.json')}

Keys and display names only. The descriptions and accent colours in the JSON
belong to the pickers the two clients draw; the backend has its own
SCHOOL_SUBJECT_DESCRIPTIONS, written for quest creators, which is a different
audience and deliberately a different list.
"""

# Transcript order. The keys are a database enum; the names are what a
# transcript line says.
SUBJECT_KEYS = (
${keys}
)

SUBJECT_NAMES = {
${pyDict(subjects.map((s) => [s.key, s.name]))}
}
`;
}

// ------------------------------------------------------------------- credits

function tsCredits() {
  const rows = credits.subjects
    .map(
      (c) => `  {
    key: ${ts(c.key)},
    credits: ${c.credits},
    transcriptName: ${ts(c.transcriptName)},
    description: ${ts(c.description)},
  },`,
    )
    .join('\n');

  return `/**
 * ${BANNER('shared/data/credits.json').split('\n').join('\n * ')}
 *
 * The arithmetic over this data is in ../credits.ts. Import that, not this.
 */

export interface CreditRequirement {
  key: string;
  /** Credits this subject must contribute to the 24-credit diploma. */
  credits: number;
  /** The LONG form an official transcript prints — 'Mathematics', not 'Math'. */
  transcriptName: string;
  description: string;
}

/** XP that equals one accredited high-school credit. */
export const XP_PER_CREDIT = ${credits.xpPerCredit};

export const TOTAL_CREDITS_REQUIRED = ${pyf(credits.totalCreditsRequired)};

/** The one bucket defined as "anything", so the only one surplus may flow into. */
export const ELECTIVE_SUBJECT = ${ts(credits.electiveSubject)};

/** Youngest age that may take a credit class (quest_type='class'). */
export const CLASS_MIN_AGE = ${credits.classMinAge};

/** In transcript order. */
export const CREDIT_REQUIREMENTS_DATA: readonly CreditRequirement[] = [
${rows}
];
`;
}

function pyCredits() {
  return `"""${BANNER('shared/data/credits.json')}

The credit requirement table, the XP conversion rate and the formal transcript
names. Before this these were five separate declarations across backend/ and
one on the web, kept in step by a comment asking whoever edited one to edit the
others.
"""

# XP that equals one accredited high-school credit.
XP_PER_CREDIT = ${credits.xpPerCredit}

TOTAL_CREDITS_REQUIRED = ${pyf(credits.totalCreditsRequired)}

# The one bucket defined as "anything", so the only one surplus may flow into.
ELECTIVE_SUBJECT = ${py(credits.electiveSubject)}

# Youngest age that may take a credit class (quest_type='class').
CLASS_MIN_AGE = ${credits.classMinAge}

# Credits each subject must contribute to the ${credits.totalCreditsRequired}-credit diploma.
DIPLOMA_CREDIT_REQUIREMENTS = {
${credits.subjects.map((c) => `    ${py(c.key)}: ${pyf(c.credits)},`).join('\n')}
}

# What an official transcript prints. The LONG form on purpose -- 'Mathematics',
# not 'Math'. generated/subjects.py carries the short names the pickers show.
TRANSCRIPT_SUBJECT_NAMES = {
${pyDict(credits.subjects.map((c) => [c.key, c.transcriptName]))}
}
`;
}


// ------------------------------------------------------------------- pricing
//
// One price list, three readers: the backend, the apps, and the marketing site
// (which builds on its own and cannot import shared/, so it gets its own copy
// of the same generated file). Every surface also gets PRICE_TEXT -- the
// prices already formatted -- so "$50" is spelled one way everywhere, and the
// help center and CRM emails in the database can name a price as
// {{price.<key>}} and have the backend fill it in.

/** "$50", "$2,400", "$0.30" -- whole dollars print without cents. */
const usd = (cents) => {
  const dollars = cents / 100;
  return Number.isInteger(dollars)
    ? `$${dollars.toLocaleString('en-US')}`
    : `$${dollars.toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;
};

function pricingChecks() {
  const a = pricing.academy;
  const l = pricing.licensed;
  const o = pricing.openEd;
  const problems = [];
  // The rule the copy states: a year of tuition is the included credits.
  if (a.tuitionMonthlyCents * 12 !== a.creditsIncludedPerYear * a.creditCents) {
    problems.push('academy: 12 months of tuition must equal creditsIncludedPerYear credits at creditCents');
  }
  if (o.yearCents !== o.creditsIncludedPerYear * l.creditCents) {
    problems.push('openEd: yearCents must equal creditsIncludedPerYear credits at licensed.creditCents');
  }
  // Tanner, 2026-10-13: accelerated credit is priced above accrediting
  // transfer credit and is never discounted.
  if (pricing.accelerated.creditCents < pricing.transfer.unaccreditedCreditCents) {
    problems.push('accelerated: creditCents must not be below transfer.unaccreditedCreditCents');
  }
  if (a.fullTimeMonthlyCents < a.tuitionMonthlyCents) {
    problems.push('academy: fullTimeMonthlyCents includes tuition, so it cannot be less than it');
  }
  if (problems.length) {
    console.error('shared/data/pricing.json does not add up:\n' + problems.map((p) => `  ${p}`).join('\n'));
    process.exit(1);
  }
}

/** The formatted prices, keyed by the name copy uses. */
function priceText() {
  const a = pricing.academy;
  const l = pricing.licensed;
  const o = pricing.openEd;
  const t = pricing.transfer;
  const years = credits.totalCreditsRequired / a.creditsIncludedPerYear;
  return {
    academyTuitionMonthly: usd(a.tuitionMonthlyCents),
    academyFamilyCapMonthly: usd(a.familyCapMonthlyCents),
    academyTuitionYearly: usd(a.tuitionMonthlyCents * 12),
    academyDiplomaTotal: usd(a.tuitionMonthlyCents * 12 * years),
    academyCreditsIncludedPerYear: String(a.creditsIncludedPerYear),
    academyCredit: usd(a.creditCents),
    academyHalfCredit: usd(a.creditCents / 2),
    fullTimeMonthly: usd(a.fullTimeMonthlyCents),
    acceleratedCredit: usd(pricing.accelerated.creditCents),
    acceleratedHalfCredit: usd(pricing.accelerated.creditCents / 2),
    licensedCredit: usd(l.creditCents),
    licensedHalfCredit: usd(l.creditCents / 2),
    licensePerStudentYearly: usd(l.licensePerStudentYearCents),
    transferAccredited: pricing.transfer.accreditedCreditCents === 0 ? 'free' : usd(pricing.transfer.accreditedCreditCents),
    // One price for unaccredited prior learning since 2026-10-14. The
    // Private/Licensed names stay because database copy (help articles, CRM
    // funnels) already uses them, and an unknown name prints as written.
    transferUnaccredited: usd(t.unaccreditedCreditCents),
    transferUnaccreditedHalfCredit: usd(t.unaccreditedCreditCents / 2),
    transferUnaccreditedPrivate: usd(t.unaccreditedCreditCents),
    transferUnaccreditedLicensed: usd(t.unaccreditedCreditCents),
    maxTransferCredits: String(pricing.transfer.maxTransferCredits),
    openEdYearly: usd(o.yearCents),
    openEdCreditsIncludedPerYear: String(o.creditsIncludedPerYear),
    openEdPriorLearningWindowDays: String(o.priorLearningWindowDays),
    // What an OpenEd family pays in the marketplace: Optio's price plus
    // OpenEd's fee.
    openEdPriorLearningHalfCredit: usd(t.unaccreditedCreditCents / 2 + o.marketplaceFeeHalfCreditCents),
    optioCourseForSchools: usd(pricing.optioCourseForSchools.perStudentCents),
    diplomaCredits: String(credits.totalCreditsRequired),
    diplomaYears: String(years),
  };
}

const stripComments = (v) => (Array.isArray(v) ? v.map(stripComments)
  : v && typeof v === 'object'
    ? Object.fromEntries(Object.entries(v).filter(([k]) => !k.startsWith('_')).map(([k, x]) => [k, stripComments(x)]))
    : v);

function tsPricing() {
  pricingChecks();
  const data = stripComments(pricing);
  const text = priceText();
  return `/**
 * ${BANNER('shared/data/pricing.json').split('\n').join('\n * ')}
 *
 * Integer cents in PRICING; the same prices formatted for copy in PRICE_TEXT.
 */

export const PRICING = ${JSON.stringify(data, null, 2)} as const;

/** Formatted for copy: '$50', '$2,400', '2.9% + $0.30'. */
export const PRICE_TEXT = ${JSON.stringify(text, null, 2)} as const;

export type PriceTextKey = keyof typeof PRICE_TEXT;
`;
}

function pyLiteral(v, indent = '') {
  if (v === null) return 'None';
  if (typeof v === 'boolean') return v ? 'True' : 'False';
  if (typeof v === 'number') return String(v);
  if (typeof v === 'string') return py(v);
  if (Array.isArray(v)) return `[${v.map((x) => pyLiteral(x, indent)).join(', ')}]`;
  const inner = indent + '    ';
  return `{\n${Object.entries(v).map(([k, x]) => `${inner}${py(k)}: ${pyLiteral(x, inner)},`).join('\n')}\n${indent}}`;
}

function pyPricing() {
  pricingChecks();
  return `"""${BANNER('shared/data/pricing.json')}

Integer cents in PRICING; the same prices formatted for copy in PRICE_TEXT.
utils/pricing_text.py fills {{price.<key>}} in database-held copy from
PRICE_TEXT.
"""

from typing import Any, Dict

PRICING: Dict[str, Any] = ${pyLiteral(stripComments(pricing))}

PRICE_TEXT: Dict[str, str] = ${pyLiteral(priceText())}
`;
}

// --------------------------------------------------------------------- drive

const OUTPUTS = [
  [join(SHARED, 'generated', 'pillars.ts'), tsPillars()],
  [join(SHARED, 'generated', 'subjects.ts'), tsSubjects()],
  [join(REPO, 'backend', 'generated', 'pillars.py'), pyPillars()],
  [join(REPO, 'backend', 'generated', 'subjects.py'), pySubjects()],
  [join(SHARED, 'generated', 'credits.ts'), tsCredits()],
  [join(REPO, 'backend', 'generated', 'credits.py'), pyCredits()],
  [join(SHARED, 'generated', 'pricing.ts'), tsPricing()],
  [join(REPO, 'backend', 'generated', 'pricing.py'), pyPricing()],
  // The marketing site builds from marketing/ alone and cannot reach shared/.
  [join(REPO, 'marketing', 'src', 'data', 'pricing.generated.ts'), tsPricing()],
];

const check = process.argv.includes('--check');
const drifted = [];

for (const [path, content] of OUTPUTS) {
  let current = null;
  try {
    current = readFileSync(path, 'utf8');
  } catch {
    /* missing counts as drift */
  }
  if (current === content) continue;
  if (check) {
    drifted.push(relative(REPO, path));
  } else {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
    console.log(`wrote ${relative(REPO, path)}`);
  }
}

if (check) {
  if (drifted.length) {
    console.error(
      'Generated constants are out of date:\n' +
        drifted.map((f) => `  ${f}`).join('\n') +
        '\n\nThese files are emitted from shared/data/*.json. Run `npm run generate`\n' +
        'from the repo root and commit the result. If you edited a generated file\n' +
        'by hand, move the change into the JSON instead — the JSON is the source.',
    );
    process.exit(1);
  }
  console.log('Generated constants are in sync with shared/data/.');
} else if (OUTPUTS.every(([p, c]) => readFileSync(p, 'utf8') === c)) {
  console.log('Generated constants are up to date.');
}
